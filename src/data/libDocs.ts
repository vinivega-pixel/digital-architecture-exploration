const clean = (s: string) => s.toLowerCase().replace(/[\s\u00a0]/g, '').replace(/[—–-]/g, '-');

export const findLibDoc = (title: string): LibDoc | undefined => {
  const t = clean(title);
  const num = t.match(/(сп|гост|рд)-?([\d.]+[\d]*)/);
  if (num) {
    const hit = libDocs.find((d) => {
      const c = clean(d.code);
      return c.startsWith(num[1]) && c.includes(num[2].replace(/\.$/, ''));
    });
    if (hit) return hit;
  }
  if (/земельныйкодекс|зкрф/.test(t)) return libDocs.find((d) => d.code.includes('136-ФЗ'));
  if (/7-фз|охранеокружающей/.test(t)) return libDocs.find((d) => d.code.includes('7-ФЗ'));
  if (/145/.test(t) && /пп|постановлен/.test(t)) return libDocs.find((d) => d.code.includes('145'));
  if (/421/.test(t)) return libDocs.find((d) => d.code.includes('421'));
  if (/1039/.test(t)) return libDocs.find((d) => d.code.includes('1039'));
  return undefined;
};

export const libDocUrl = (d: LibDoc) => DOCS_BASE + d.file;
