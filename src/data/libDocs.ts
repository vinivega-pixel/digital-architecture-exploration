const clean = (s: string) =>
  s.toLowerCase().replace(/[\s\u00a0]/g, '').replace(/[—–−-]/g, '-').replace(/[№n]/g, 'n');

const byCode = (part: string) => libDocs.find((d) => clean(d.code).includes(clean(part)));

export const findLibDoc = (title: string): LibDoc | undefined => {
  const t = clean(title);

  const num = t.match(/(сп|гост|рд)р?-?([\d]+[\d.-]*)/);
  if (num) {
    const base = num[2].replace(/[.-]+$/, '');
    const hit = libDocs.find((d) => {
      const c = clean(d.code);
      return c.startsWith(num[1] === 'гост' ? 'гост' : num[1]) && c.includes(base);
    });
    if (hit) return hit;
  }

  const fz = t.match(/n?(\d+)-фз/) ?? t.match(/фз-(\d+)/);
  if (fz) {
    const hit = byCode(`${fz[1]}-фз`);
    if (hit) return hit;
  }

  if (/градостроительныйкодекс|гркрф/.test(t)) return byCode('190-фз');
  if (/земельныйкодекс|зкрф/.test(t)) return byCode('136-фз');
  if (/пуэ|устройствеэлектроустановок/.test(t)) return byCode('пуэ');
  if (/санпин/.test(t)) return /отход|содержаниетерритор/.test(t) ? byCode('2.1.3684') : byCode('1.2.3685');

  const pp = t.match(/(?:пп|постановлен\w*)[^\d]{0,14}(\d{2,4})/);
  if (pp) {
    const hit = byCode(`ппрфn${pp[1]}`);
    if (hit) return hit;
  }

  const prikaz = t.match(/(?:приказ\w*|минстро\w*)[^\d]{0,20}(\d{2,4})[\s/]*пр/);
  if (prikaz) {
    const hit = byCode(`n${prikaz[1]}-пр`);
    if (hit) return hit;
  }

  return undefined;
};

export const libDocUrl = (d: LibDoc) => DOCS_BASE + d.file;
